def test_python_parsing_symbols():
    py_code = (
        "import os\n"
        "\n"
        "def helper():\n"
        "    return 42\n"
        "\n"
        "@decorator\n"
        "async def do_work(x):\n"
        "    def inner():\n"
        "        pass\n"
        "    return x + 1\n"
        "\n"
        "class MyService:\n"
        "    \"\"\"Service doc.\"\"\"\n"
        "    value = 10\n"
        "\n"
        "    @property\n"
        "    def val(self):\n"
        "        return self.value\n"
    )
    lines = py_code.splitlines()
    chunks = parser.parse_file("service.py", "python", py_code)

    # Function helper
    c_helper = next((c for c in chunks if c.symbol == "helper"), None)
    assert c_helper is not None
    assert c_helper.kind == "function"
    assert c_helper.start_line == 3
    assert c_helper.end_line == 4

    # Async function with decorator
    c_work = next((c for c in chunks if c.symbol == "do_work"), None)
    assert c_work is not None
    assert c_work.kind == "function"
    assert c_work.start_line == 6  # includes @decorator
    assert c_work.end_line == 10

    # Class MyService (header chunk)
    c_class = next((c for c in chunks if c.symbol == "MyService"), None)
    assert c_class is not None
    assert c_class.kind == "class"
    assert c_class.start_line == 12
    assert c_class.end_line == 14  # up to first method, blank line trimmed

    # Method MyService.val with decorator
    c_method = next((c for c in chunks if c.symbol == "MyService.val"), None)
    assert c_method is not None
    assert c_method.kind == "method"
    assert c_method.start_line == 16  # includes @property
    assert c_method.end_line == 18

    # Invariant assertion
    for c in chunks:
        expected = "\n".join(lines[c.start_line - 1 : c.end_line])
        assert c.code == expected

