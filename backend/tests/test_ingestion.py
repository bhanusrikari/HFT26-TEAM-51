def test_download_github_zip_success(monkeypatch):
    bio = io.BytesIO()
    with zipfile.ZipFile(bio, "w") as zf:
        zf.writestr("repo-main/hello.py", "print('hello')\n")
    zip_bytes = bio.getvalue()

    def mock_get(self, url, *args, **kwargs):
        if "api.github.com" in url:
            return httpx.Response(200, json={"default_branch": "main"})
        return httpx.Response(404)

    def mock_stream(self, method, url, *args, **kwargs):
        class MockStream:
            status_code = 200
            def __enter__(self): return self
            def __exit__(self, *args): pass
            def iter_bytes(self, chunk_size=65536):
                yield zip_bytes
        return MockStream()

    monkeypatch.setattr(httpx.Client, "get", mock_get)
    monkeypatch.setattr(httpx.Client, "stream", mock_stream)

    with tempfile.NamedTemporaryFile(suffix=".zip", delete=False) as tmp:
        dest_zip = tmp.name

    try:
        sources.download_github_zip("owner", "repo", None, dest_zip)
        assert os.path.getsize(dest_zip) == len(zip_bytes)
    finally:
        if os.path.exists(dest_zip):
            os.unlink(dest_zip)

