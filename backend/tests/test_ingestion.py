def test_zip_slip_rejection():
    # Build a malicious zip with ../evil.txt
    bio = io.BytesIO()
    with zipfile.ZipFile(bio, "w") as zf:
        zf.writestr("../evil.txt", "hacked")

    with tempfile.NamedTemporaryFile(suffix=".zip", delete=False) as tmp_zip:
        tmp_zip.write(bio.getvalue())
        tmp_zip_path = tmp_zip.name

    with tempfile.TemporaryDirectory() as dest_dir:
        try:
            with pytest.raises(ValueError, match="Zip-slip detected"):
                sources.extract_zip_safely(tmp_zip_path, dest_dir)
        finally:
            if os.path.exists(tmp_zip_path):
                os.unlink(tmp_zip_path)

