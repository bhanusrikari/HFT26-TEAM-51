# 4. Invariant Test on Sample Repo Fixture
# -------------------------------------------------------------------------

def test_sample_repo_exact_line_invariant():
    index = indexer.build_index(FIXTURE_DIR, name="sample-repo")
    assert len(index.files) > 0
    assert len(index.chunks) > 0

    # Ensure skipped keys are all present
    assert "excluded_dir" in index.skipped
    assert "generated" in index.skipped
    assert "too_large" in index.skipped
    assert "binary" in index.skipped
    assert "unsupported" in index.skipped
    assert "limit" in index.skipped

    # Verify that junk files were skipped
    indexed_paths = {f.path for f in index.files}
    assert not any("node_modules" in p for p in indexed_paths)
    assert not any("dist" in p for p in indexed_paths)
    assert not any(p.endswith(".png") for p in indexed_paths)
    assert not any(p.endswith(".lock") or "package-lock" in p for p in indexed_paths)
    assert not any("generated.py" in p for p in indexed_paths)

    # Invariant assertion for EVERY chunk
    for chunk in index.chunks:
        full_path = os.path.join(FIXTURE_DIR, chunk.file_path)
        with open(full_path, "r", encoding="utf-8") as f:
            lines = f.read().splitlines()

        assert chunk.chunk_id == f"{chunk.file_path}:{chunk.start_line}-{chunk.end_line}"
        expected_code = "\n".join(lines[chunk.start_line - 1 : chunk.end_line])
        assert chunk.code == expected_code, f"Invariant violated in {chunk.chunk_id}"

