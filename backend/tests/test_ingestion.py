def test_parse_github_url_valid():
    o, r, b = sources.parse_github_url("https://github.com/torvalds/linux")
    assert (o, r, b) == ("torvalds", "linux", None)

    o, r, b = sources.parse_github_url("https://github.com/facebook/react.git")
    assert (o, r, b) == ("facebook", "react", None)

    o, r, b = sources.parse_github_url("https://github.com/vuejs/core/")
    assert (o, r, b) == ("vuejs", "core", None)

    o, r, b = sources.parse_github_url("https://github.com/pallets/flask/tree/main")
    assert (o, r, b) == ("pallets", "flask", "main")

    o, r, b = sources.parse_github_url("https://github.com/owner/repo/tree/feature/sub/branch")
    assert (o, r, b) == ("owner", "repo", "feature/sub/branch")

def test_parse_github_url_invalid():
    with pytest.raises(ValueError, match="Invalid host"):
        sources.parse_github_url("https://gitlab.com/owner/repo")

    with pytest.raises(ValueError, match="Invalid host"):
        sources.parse_github_url("https://evil.github.com.attacker.com/repo")

    with pytest.raises(ValueError):
        sources.parse_github_url("https://github.com/")

    with pytest.raises(ValueError):
        sources.parse_github_url("not-a-url")

