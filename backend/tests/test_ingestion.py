def test_large_chunk_splitting():
    large_code = "\n".join([f"line_{i} = {i}" for i in range(1, 201)])
    chunks = parser.parse_file("large.py", "python", large_code)
    for c in chunks:
        num_lines = c.end_line - c.start_line + 1
        assert num_lines <= 80, f"Chunk {c.chunk_id} exceeded 80 lines: {num_lines}"
        expected = "\n".join(large_code.splitlines()[c.start_line - 1 : c.end_line])
        assert c.code == expected

